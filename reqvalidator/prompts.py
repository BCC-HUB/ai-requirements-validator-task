def _criteria_block(criteria) -> str:
    return "\n".join(f"{c.code} «{c.name}» ({c.source}): {c.question}" for c in criteria)


def _doc_block(numbered: str) -> str:
    return f"ДОКУМЕНТ (пронумерованные строки):\n<<<ДОКУМЕНТ\n{numbered}\nДОКУМЕНТ>>>"


def _schema(example: dict) -> str:
    return "СХЕМА ОТВЕТА (пример структуры; значения — иллюстрация):\n" + json.dumps(
        example, ensure_ascii=False, indent=1
    )


