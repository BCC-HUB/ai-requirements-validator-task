def segment_prompt(numbered: str) -> str:
    return f"""ЗАДАЧА: выделить из документа отдельные требования («нарезка») для последующей проверки.

Что считать требованием: любое утверждение, задающее обязательное поведение, свойство, ограничение, правило, данные, интерфейс, интеграцию, внешний вид или критерий приёмки системы. Это в том числе цели, архитектурные решения, описание процесса и UI, нефункциональные требования, требования к данным и интеграции, спецификации API (метод, URL, авторизация, параметры, ответы, коды статусов, правила обработки), критерии приёмки.

Правила нарезки:
- Пункт с собственным идентификатором («Ф-1.», «REQ-12», «1.» в нумерованном списке) — ОДНО требование, даже если в нём несколько предложений (атомарность проверяется позже — не дроби такие пункты).
- doc_id — ТОЛЬКО идентификатор, который буквально написан в документе: код пункта («Ф-1», «REQ-12»); номер пункта нумерованного списка вместе с разделом («Алгоритм обработки, п. 3»); код ответа, которым озаглавлен пункт («Статус 401»). НЕ придумывай идентификаторы: у строк таблиц, критериев приёмки без номеров и ненумерованного текста doc_id = null.
- locator — короткая подпись места для читателя, когда doc_id = null и место неочевидно: «Общие параметры: REST type», «Query-параметр amount», «Критерии приёмки, строка 2». Иначе null.
- Ненумерованный абзац: отдельное требование на каждую самостоятельную обязанность или свойство (обычно — на предложение).
- Таблица параметров или полей: одна строка таблицы — одно требование. Таблица общих параметров API: строка — требование, если она задаёт поведение или свойство интерфейса (описание метода, HTTP-метод, URL, авторизация, пример вызова); справочные строки без требований (автор, проект) — в excluded.
- Критерии приёмки: каждая строка таблицы — отдельное требование, kind = "acceptance".
- Коды ответа: каждый код со своим описанием и примером — одно требование.
- НЕ являются требованиями (перечисли в excluded с причиной): заголовки, служебные метаданные (наименование задачи, роли владельцев, ссылка на JIRA), шаблонные чек-листы ревью, блоки согласования, пустые разделы и заглушки, вводные пояснения о самом документе. Они будут оценены на уровне всего набора.
- quote — ДОСЛОВНЫЙ текст требования (Markdown-разметку можно опустить; слова и порядок — как в документе). Для строки таблицы — содержимое ячеек через « | ».
- line_start / line_end — диапазон строк требования.
- summary — суть своими словами, не длиннее 12 слов.
- section — путь раздела через « › », например «Часть A › Функциональные требования».
- kind — одно из: goal, functional, ui, process, architecture, nonfunctional, data, integration, api, acceptance, other.
- Сохраняй порядок документа. Ничего не пропускай: каждая непустая строка (кроме заголовков и разделителей таблиц) должна войти либо в требование, либо в excluded.

{_schema(SEGMENT_EXAMPLE)}

{_doc_block(numbered)}"""


def coverage_repair_prompt(
    numbered: str,
    uncovered: list[tuple[int, str]],
    known: str,
    reconsider: list[tuple[int, str]] | None = None,
) -> str:
    lines = "\n".join(f"L{no}| {text}" for no, text in uncovered) or "нет"
    second = ""
    if reconsider:
        rows = "\n".join(f"L{no}| {text}" for no, text in reconsider)
        second = f"""

Следующие строки ты отнёс к исключённым, но они похожи на требования (содержат слова обязательности или находятся в разделе требований, критериев приёмки, API, данных). Пересмотри их по правилам нарезки: требование — в requirements, иначе — в excluded с конкретной причиной:

{rows}"""
    return f"""ЗАДАЧА: дополнить нарезку требований. Следующие строки документа не вошли ни в одно выделенное требование и не отмечены как исключённые:

{lines}{second}

Уже выделенные требования (ID — строки — суть):
{known}

Для каждой из этих строк реши: это требование (добавь в requirements по правилам нарезки — дословная цитата, doc_id, kind, раздел, строки, summary) или не требование (добавь в excluded с причиной: заголовок таблицы, метаданные, пояснение и т. п.). Не повторяй уже выделенные требования.

{_schema(SEGMENT_EXAMPLE)}

{_doc_block(numbered)}"""


